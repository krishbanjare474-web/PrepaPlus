function shuffle(arr=[]){
    return arr.sort(()=>Math.random()-0.5);
}

loadQuestions();

function loadQuestions(){

    let quiz=document.getElementById("quiz");
    let html="";

    questions.forEach((q,index)=>{

        q.o=shuffle(q.o);

        html+=`
        <div class="question">

        <h3>Q${index+1}. ${q.q}</h3>
        `;

        q.o.forEach(option=>{

            html+=`
            <label id="q${index}_${option}">
            <input type="radio" name="q${index}" value="${option}">
            ${option}
            </label>
            `;

        });

        html+=`</div>`;

    });

    quiz.innerHTML=html;
}

function checkResult(){

    let score = 0;
    let correct = 0;
    let wrong = 0;

    questions.forEach((q, index) => {

        let selected = document.querySelector(
            `input[name="q${index}"]:checked`
        );

        if(selected){

            if(selected.value === q.a){

                score++;
                correct++;

                let right = document.getElementById(
                    `q${index}_${q.a}`
                );

                if(right){
                    right.innerHTML += " ✔️";
                    right.style.background = "#b7f7c1";
                }

            } else {

                wrong++;

                let wrongAns = document.getElementById(
                    `q${index}_${selected.value}`
                );

                if(wrongAns){
                    wrongAns.innerHTML += " ❌";
                    wrongAns.style.background = "#ffb3b3";
                }

                let correctAns = document.getElementById(
                    `q${index}_${q.a}`
                );

                if(correctAns){
                    correctAns.innerHTML += " ✔️";
                    correctAns.style.background = "#b7f7c1";
                }
            }
        }
    });

    document.getElementById("result").innerHTML = `
        <h2>🎯 Result</h2>
        <p>Score: ${score}/${questions.length}</p>
        <p>सही: ${correct} | गलत: ${wrong}</p>
    `;
}