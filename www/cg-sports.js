// Options Shuffle
function shuffle(array) {
    return array.sort(() => Math.random() - 0.5);
}


// Questions Load
function loadQuestions() {

    const container = document.getElementById("question-container");

    container.innerHTML = "";

    questions.forEach((item, index) => {

        let options = shuffle([...item.o]);

        const card = document.createElement("div");
        card.className = "question-card";

        let html = `
            <h3>Q${index + 1}. ${item.q}</h3>
        `;

        options.forEach(option => {

            html += `
                <label class="option">
                    <input type="radio"
                           name="question${index}"
                           value="${option}">
                    ${option}
                </label>
            `;

        });

        card.innerHTML = html;

        container.appendChild(card);
    });
}


// Result Check
function checkResult() {

    let score = 0;
    let attempted = 0;

    questions.forEach((item, index) => {

        const selected = document.querySelector(
            `input[name="question${index}"]:checked`
        );

        const options = document.querySelectorAll(
            `input[name="question${index}"]`
        );

        if (selected) {

            attempted++;

            if (selected.value === item.a) {
                score++;
            }
        }

        options.forEach(input => {

            const label = input.parentElement;

            label.classList.remove("correct", "wrong");

            if (input.value === item.a) {
                label.classList.add("correct");
            }

            if (
                selected &&
                input === selected &&
                selected.value !== item.a
            ) {
                label.classList.add("wrong");
            }

            input.disabled = true;
        });
    });


    const wrong = attempted - score;
    const notAttempted = questions.length - attempted;

    document.getElementById("result").innerHTML = `
        🎯 <strong>Result</strong><br><br>

        कुल प्रश्न: ${questions.length}<br>
        ✅ सही उत्तर: ${score}<br>
        ❌ गलत उत्तर: ${wrong}<br>
        ⭕ नहीं किए: ${notAttempted}<br><br>

        <strong>आपका Score: ${score} / ${questions.length}</strong>
    `;

    document.getElementById("submit-btn").disabled = true;

    document.getElementById("submit-btn").innerText =
        "✔️ Test Checked";

    window.scrollTo({
        top: document.body.scrollHeight,
        behavior: "smooth"
    });
}


// Page Load
loadQuestions();