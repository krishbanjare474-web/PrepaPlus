function loadQuestions() {

    let quiz = document.getElementById("quiz");

    quiz.innerHTML = "";

    questions.forEach((q, index) => {

        let html = `
        <div class="question">

            <h3>${index + 1}. ${q.q}</h3>

            <label id="q${index}_A">
                <input type="radio" name="q${index}" value="A">
                ${q.options[0]}
            </label>

            <label id="q${index}_B">
                <input type="radio" name="q${index}" value="B">
                ${q.options[1]}
            </label>

            <label id="q${index}_C">
                <input type="radio" name="q${index}" value="C">
                ${q.options[2]}
            </label>

            <label id="q${index}_D">
                <input type="radio" name="q${index}" value="D">
                ${q.options[3]}
            </label>

        </div>
        `;

        quiz.innerHTML += html;
    });
}


function checkResult() {

    let score = 0;
    let correct = 0;
    let wrong = 0;

    questions.forEach((q, index) => {

        let selected = document.querySelector(
            `input[name="q${index}"]:checked`
        );

        // पहले सभी options का color reset
        ["A", "B", "C", "D"].forEach(option => {
            let element = document.getElementById(`q${index}_${option}`);

            element.style.background = "";
            element.innerHTML = element.innerHTML.replace(" ✔️", "");
            element.innerHTML = element.innerHTML.replace(" ❌", "");
        });


        if (selected) {

            if (selected.value === q.a) {

                score++;
                correct++;

                let right = document.getElementById(
                    `q${index}_${q.a}`
                );

                right.style.background = "#b7f7c1";
                right.innerHTML += " ✔️";

            } else {

                wrong++;

                // चुना हुआ गलत answer
                let wrongAnswer = document.getElementById(
                    `q${index}_${selected.value}`
                );

                wrongAnswer.style.background = "#ffb3b3";
                wrongAnswer.innerHTML += " ❌";


                // सही answer
                let correctAnswer = document.getElementById(
                    `q${index}_${q.a}`
                );

                correctAnswer.style.background = "#b7f7c1";
                correctAnswer.innerHTML += " ✔️";
            }
        }

    });


    document.getElementById("result").innerHTML = `
        <h2>📊 Result</h2>
        <p>Score: ${score}/${questions.length}</p>
        <p>सही: ${correct} | गलत: ${wrong}</p>
    `;
}


