function loadQuestions() {
  const quiz = document.getElementById("quiz");
  let html = "";

  questions.forEach((q, index) => {
    html += `<div class="question">
      <h3>Q${index + 1}. ${q.q}</h3>`;

    q.o.forEach(option => {
      html += `
      <label id="option${index}-${option}">
        <input type="radio" name="q${index}" value="${option}">
        ${option}
      </label><br>`;
    });

    html += `</div>`;
  });

  quiz.innerHTML = html;
}