// ===============================
// OPTIONS SHUFFLE
// ===============================

function shuffle(array) {
    return array.sort(() => Math.random() - 0.5);
}


// ===============================
// LOAD QUESTIONS
// ===============================

function loadQuestions() {

    const container = document.getElementById("quiz");

    if (!container) return;

    container.innerHTML = "";

    questions.forEach((item, index) => {

        let options = shuffle([...item.o]);

        const questionBox = document.createElement("div");

        questionBox.className = "question-box";

        questionBox.innerHTML = `
            <h3>${index + 1}. ${item.q}</h3>

            <div class="options">

                ${options.map(option => `
                    <label>
                        <input type="radio"
                               name="q${index}"
                               value="${option}">
                        <span>${option}</span>
                    </label>
                `).join("")}

            </div>
        `;

        container.appendChild(questionBox);
    });
}


// ===============================
// CHECK RESULT
// ===============================

function checkResult() {

    let score = 0;
    let attempted = 0;
    let correct = [];
    let wrong = [];

    questions.forEach((item, index) => {

        const selected =
            document.querySelector(`input[name="q${index}"]:checked`);

        if (selected) {

            attempted++;

            const labels =
                document.querySelectorAll(`input[name="q${index}"]`);

            labels.forEach(input => {

                const label = input.parentElement;

                label.style.background = "";
                label.style.color = "";

                if (input.value === item.a) {
                    label.style.background = "#d4edda";
                    label.style.color = "#155724";
                }

            });

            if (selected.value === item.a) {

                score++;
                correct.push(index + 1);

            } else {

                wrong.push(index + 1);

                selected.parentElement.style.background = "#f8d7da";
                selected.parentElement.style.color = "#721c24";
            }
        }
    });


    const result = document.getElementById("result");

    if (result) {

        result.innerHTML = `
            <div style="
                padding:20px;
                margin-top:20px;
                border-radius:12px;
                background:#f8f9fa;
                text-align:center;
            ">

                <h2>🎯 आपका परिणाम</h2>

                <h3>
                    Score: ${score} / ${questions.length}
                </h3>

                <p>
                    ✅ सही उत्तर: ${correct.length}
                </p>

                <p>
                    ❌ गलत उत्तर: ${wrong.length}
                </p>

                <p>
                    📝 Attempted: ${attempted}
                </p>

            </div>
        `;
    }

    window.scrollTo({
        top: document.body.scrollHeight,
        behavior: "smooth"
    });
}


