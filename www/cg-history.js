// Options को shuffle करने का function
function shuffle(array) {
    return array.sort(() => Math.random() - 0.5);
}


// Questions load करना
function loadQuestions() {

    const quiz = document.getElementById("quiz");

    quiz.innerHTML = "";

    questions.forEach((item, index) => {

        const box = document.createElement("div");

        box.className = "question-box";

        let options = shuffle([...item.o]);

        let html = `
            <div class="question">
                <h3>${index + 1}. ${item.q}</h3>
        `;

        options.forEach(option => {

            html += `
                <label class="option">
                    <input type="radio"
                           name="q${index}"
                           value="${option}">
                    <span>${option}</span>
                </label>
            `;

        });

        html += `</div>`;

        box.innerHTML = html;

        quiz.appendChild(box);
    });
}


// Result check करना
function checkResult() {

    let score = 0;
    let attempted = 0;

    questions.forEach((item, index) => {

        const options = document.querySelectorAll(
            `input[name="q${index}"]`
        );

        const selected = document.querySelector(
            `input[name="q${index}"]:checked`
        );

        if (selected) {
            attempted++;
        }

        options.forEach(input => {

            const label = input.closest(".option");

            // Pehle reset
            label.style.backgroundColor = "";
            label.style.color = "";

            // Sahi answer ko GREEN
            if (input.value === item.a) {
                label.style.backgroundColor = "#d4edda";
                label.style.color = "#155724";
                label.style.border = "2px solid #28a745";
            }

            // User ne galat answer select kiya to RED
            if (selected && input === selected && selected.value !== item.a) {
                label.style.backgroundColor = "#f8d7da";
                label.style.color = "#721c24";
                label.style.border = "2px solid #dc3545";
            }
        });

        if (selected && selected.value === item.a) {
            score++;
        }
    });

    const result = document.getElementById("result");

    result.innerHTML = `
        <h2>📊 Result</h2>
        <p>कुल प्रश्न: ${questions.length}</p>
        <p>Attempted: ${attempted}</p>
        <p>सही उत्तर: ${score}</p>
        <p>गलत उत्तर: ${attempted - score}</p>
        <h3>🎯 Score: ${score} / ${questions.length}</h3>
    `;

    window.scrollTo({
        top: document.body.scrollHeight,
        behavior: "smooth"
    });
}