let userAnswers = new Array(questions.length).fill(null);

function shuffle(array) {
    return array.sort(() => Math.random() - 0.5);
}

function loadQuestions() {

    const quiz = document.getElementById("quiz");

    if (!quiz) {
        console.log("quiz नाम का container नहीं मिला");
        return;
    }

    quiz.innerHTML = "";

    questions.forEach((question, index) => {

        const questionBox = document.createElement("div");
        questionBox.className = "question";

        let html = `
            <h3>${index + 1}. ${question.q}</h3>
        `;

        const options = question.options.map((text, i) => ({
            text: text,
            key: String.fromCharCode(65 + i)
        }));

        shuffle(options);

        options.forEach(option => {

            html += `
                <label
                    class="option"
                    id="q${index}_${option.key}"
                >
                    <input
                        type="radio"
                        name="question${index}"
                        value="${option.key}"
                        onchange="saveAnswer(${index}, '${option.key}')"
                    >
                    ${option.text}
                </label>
            `;

        });

        questionBox.innerHTML = html;
        quiz.appendChild(questionBox);

    });

}

function saveAnswer(index, answer) {
    userAnswers[index] = answer;
}

function checkResult() {

    let score = 0;
    let correct = 0;
    let wrong = 0;
    let unanswered = 0;

    questions.forEach((question, index) => {

        const userAnswer = userAnswers[index];

        if (userAnswer === null) {

            unanswered++;

        }
        else if (userAnswer === question.a) {

            score++;
            correct++;

            const correctBox = document.getElementById(
                `q${index}_${question.a}`
            );

            if (correctBox) {
                correctBox.style.backgroundColor = "#d4edda";
                correctBox.style.color = "#155724";
            }

        }
        else {

            wrong++;

            const wrongBox = document.getElementById(
                `q${index}_${userAnswer}`
            );

            const correctBox = document.getElementById(
                `q${index}_${question.a}`
            );

            if (wrongBox) {
                wrongBox.style.backgroundColor = "#f8d7da";
                wrongBox.style.color = "#721c24";
            }

            if (correctBox) {
                correctBox.style.backgroundColor = "#d4edda";
                correctBox.style.color = "#155724";
            }

        }

    });

    const result = document.getElementById("result");

    if (result) {

        result.innerHTML = `
            <h2>📊 Result</h2>
            <p>✅ सही उत्तर: ${correct}</p>
            <p>❌ गलत उत्तर: ${wrong}</p>
            <p>⚪ छोड़े गए: ${unanswered}</p>
            <p>🏆 स्कोर: ${score} / ${questions.length}</p>
        `;

        result.style.display = "block";
    }

}

