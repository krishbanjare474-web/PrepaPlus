// ===============================
// OPTIONS SHUFFLE
// ===============================

function shuffle(array) {
    return array.sort(() => Math.random() - 0.5);
}


// ===============================
// LOAD QUESTIONS
// ===============================

function loadQuestions() {

    const quiz = document.getElementById("quiz");

    quiz.innerHTML = "";

    questions.forEach((item, index) => {

        let options = shuffle([...item.o]);

        let html = `
            <div class="question-card">

                <div class="question">
                    ${index + 1}. ${item.q}
                </div>
        `;

        options.forEach((option, optionIndex) => {

            html += `
                <label class="option" id="q${index}o${optionIndex}">
                    <input
                        type="radio"
                        name="question${index}"
                        value="${option}"
                    >
                    ${option}
                </label>
            `;

        });

        html += `</div>`;

        quiz.innerHTML += html;
    });
}


// ===============================
// CHECK RESULT
// ===============================

function checkResult() {

    let score = 0;
    let attempted = 0;

    questions.forEach((item, index) => {

        const selected = document.querySelector(
            `input[name="question${index}"]:checked`
        );

        const options = document.querySelectorAll(
            `input[name="question${index}"]`
        );

        options.forEach(input => {

            const label = input.parentElement;

            label.classList.remove("correct", "wrong");

            if (input.value === item.a) {
                label.classList.add("correct");
            }
        });

        if (selected) {

            attempted++;

            if (selected.value === item.a) {
                score++;
            } else {
                selected.parentElement.classList.add("wrong");
            }
        }
    });

    let wrong = attempted - score;
    let unanswered = questions.length - attempted;

    document.getElementById("result").innerHTML = `
        <div style="font-size:22px; margin-bottom:10px;">
            🎯 आपका परिणाम
        </div>

        <div>कुल प्रश्न: ${questions.length}</div>

        <div style="color:green;">
            ✔️ सही उत्तर: ${score}
        </div>

        <div style="color:red;">
            ❌ गलत उत्तर: ${wrong}
        </div>

        <div style="color:#777;">
            ⭕ नहीं किए: ${unanswered}
        </div>

        <div style="margin-top:10px; font-size:22px;">
            🏆 Score: ${score} / ${questions.length}
        </div>
    `;

    window.scrollTo({
        top: document.body.scrollHeight,
        behavior: "smooth"
    });
}


