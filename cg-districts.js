// OPTIONS SHUFFLE
// ===============================

function shuffle(array) {
    return array.sort(() => Math.random() - 0.5);
}


// ===============================
// QUESTIONS LOAD
// ===============================

function loadQuestions() {

    const quiz = document.getElementById("quiz");

    quiz.innerHTML = "";

    questions.forEach((item, index) => {

        const box = document.createElement("div");

        box.className = "question-box";

        let options = shuffle([...item.o]);

        let html = `
            <h3>${index + 1}. ${item.q}</h3>
            <div class="options">
        `;

        options.forEach(option => {

            html += `
                <label class="option">
                    <input type="radio"
                           name="q${index}"
                           value="${option}">
                    <span>${option}</span>
                </label>
            `;

        });

        html += `
            </div>
        `;

        box.innerHTML = html;

        quiz.appendChild(box);

    });

}


// ===============================
// CHECK RESULT
// ===============================

function checkResult() {

    let score = 0;
    let attempted = 0;

    questions.forEach((item, index) => {

        const selected = document.querySelector(
            `input[name="q${index}"]:checked`
        );

        const options = document.querySelectorAll(
            `input[name="q${index}"]`
        );

        options.forEach(input => {

            const label = input.parentElement;

            label.style.background = "";
            label.style.color = "";

            if (input.value === item.a) {

                label.style.background = "#d4edda";
                label.style.color = "#155724";

            }

        });

        if (selected) {

            attempted++;

            const selectedLabel = selected.parentElement;

            if (selected.value === item.a) {

                score++;

                selectedLabel.style.background = "#d4edda";
                selectedLabel.style.color = "#155724";

            } else {

                selectedLabel.style.background = "#f8d7da";
                selectedLabel.style.color = "#721c24";

            }

        }

    });


    const wrong = attempted - score;
    const unanswered = questions.length - attempted;

    document.getElementById("result").innerHTML = `
        <div class="result-box">

            <h2>📊 आपका परिणाम</h2>

            <p>🎯 कुल प्रश्न: <b>${questions.length}</b></p>

            <p>📝 Attempted: <b>${attempted}</b></p>

            <p>✅ सही उत्तर: <b>${score}</b></p>

            <p>❌ गलत उत्तर: <b>${wrong}</b></p>

            <p>⚪ नहीं किए: <b>${unanswered}</b></p>

            <h2>🏆 Score: ${score} / ${questions.length}</h2>

        </div>
    `;

    window.scrollTo({
        top: document.body.scrollHeight,
        behavior: "smooth"
    });

}


